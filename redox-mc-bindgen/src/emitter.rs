use crate::model::{ClassModel, FieldModel, JvmType, MethodModel, PrimitiveType};
use std::collections::{HashMap, HashSet};

pub fn to_snake_case(s: &str) -> String {
    let clean: String = s
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    let mut result = String::with_capacity(clean.len() + 4);
    let chars: Vec<char> = clean.chars().collect();
    for (i, &c) in chars.iter().enumerate() {
        if c.is_uppercase() {
            if i > 0
                && (chars[i - 1].is_lowercase()
                    || (chars[i - 1].is_uppercase()
                        && i + 1 < chars.len()
                        && chars[i + 1].is_lowercase()))
            {
                result.push('_');
            }
            result.extend(c.to_lowercase());
        } else {
            result.push(c);
        }
    }
    let mut collapsed = String::new();
    let mut prev_underscore = false;
    for c in result.chars() {
        if c == '_' {
            if !prev_underscore {
                collapsed.push(c);
                prev_underscore = true;
            }
        } else {
            collapsed.push(c);
            prev_underscore = false;
        }
    }
    let trimmed = collapsed.trim_matches('_');
    if trimmed.is_empty() {
        "unnamed".to_string()
    } else {
        trimmed.to_string()
    }
}

pub fn escape_rust_keyword(s: &str) -> String {
    match s {
        "as" | "break" | "const" | "continue" | "crate" | "else" | "enum" | "extern" | "false"
        | "fn" | "for" | "if" | "impl" | "in" | "let" | "loop" | "match" | "mod" | "move"
        | "mut" | "pub" | "ref" | "return" | "static" | "struct" | "super" | "trait" | "true"
        | "type" | "unsafe" | "use" | "where" | "while" | "async" | "await" | "dyn" | "yield" => {
            format!("r#{}", s)
        }
        "self" => "self_val".to_string(),
        "Self" => "SelfType".to_string(),
        other => other.to_string(),
    }
}

pub fn emit_class(class: &ClassModel) -> String {
    let mut out = String::new();

    // Module header
    out.push_str("// Auto-generated by redox-mc-bindgen. DO NOT EDIT.\n");
    out.push_str("#![allow(non_snake_case, non_camel_case_types, non_upper_case_globals, unused_imports, unused_variables, dead_code)]\n\n");
    out.push_str("use std::sync::atomic::{AtomicPtr, Ordering};\n");
    out.push_str("use jvmti_bindings::sys::jni;\n\n");

    let struct_name = &class.simple_name;

    // Struct definition
    out.push_str(&format!(
        "/// Rust JNI wrapper for Java class `{}`\n",
        class.name
    ));
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    out.push_str("#[repr(transparent)]\n");
    out.push_str(&format!("pub struct {} {{\n", struct_name));
    out.push_str("    pub raw: jni::jobject,\n");
    out.push_str("}\n\n");

    // Impl block
    out.push_str(&format!("impl {} {{\n", struct_name));
    out.push_str(&format!(
        "    pub const CLASS_NAME: &'static str = \"{}\";\n\n",
        class.name
    ));

    // Constructors and helpers
    out.push_str("    /// Wraps a raw JNI jobject without validation.\n");
    out.push_str("    #[inline]\n");
    out.push_str("    pub const fn from_raw(raw: jni::jobject) -> Self {\n");
    out.push_str("        Self { raw }\n");
    out.push_str("    }\n\n");

    out.push_str("    /// Returns the raw JNI jobject.\n");
    out.push_str("    #[inline]\n");
    out.push_str("    pub const fn as_raw(&self) -> jni::jobject {\n");
    out.push_str("        self.raw\n");
    out.push_str("    }\n\n");

    out.push_str("    /// Returns the cached jclass (as a JNI GlobalRef) for this class.\n");
    out.push_str("    pub unsafe fn get_class(env: *mut jni::JNIEnv) -> jni::jclass {\n");
    out.push_str("        static CLASS_REF: AtomicPtr<std::ffi::c_void> = AtomicPtr::new(std::ptr::null_mut());\n");
    out.push_str("        let mut cls = CLASS_REF.load(Ordering::Relaxed) as jni::jclass;\n");
    out.push_str("        if cls.is_null() {\n");
    out.push_str(&format!(
        "            let class_name_c = c\"{}\";\n",
        class.name
    ));
    out.push_str("            let local_cls = ((**env).FindClass)(env, class_name_c.as_ptr());\n");
    out.push_str("            if !local_cls.is_null() {\n");
    out.push_str("                cls = ((**env).NewGlobalRef)(env, local_cls) as jni::jclass;\n");
    out.push_str(
        "                CLASS_REF.store(cls as *mut std::ffi::c_void, Ordering::Release);\n",
    );
    out.push_str("                ((**env).DeleteLocalRef)(env, local_cls);\n");
    out.push_str("            }\n");
    out.push_str("        }\n");
    out.push_str("        cls\n");
    out.push_str("    }\n\n");

    // Compute unique method names
    let method_names = compute_method_names(&class.methods);
    let mut used_function_names = HashSet::new();

    // Emit methods
    for (idx, method) in class.methods.iter().enumerate() {
        let rust_name = &method_names[idx];
        used_function_names.insert(rust_name.clone());

        emit_method(&mut out, class, method, rust_name);
    }

    // Emit fields
    for field in &class.fields {
        emit_field(&mut out, class, field, &mut used_function_names);
    }

    out.push_str("}\n");

    out
}

fn compute_method_names(methods: &[MethodModel]) -> Vec<String> {
    let mut counts: HashMap<String, usize> = HashMap::new();
    let mut raw_names = Vec::with_capacity(methods.len());

    for method in methods {
        let base = if method.is_constructor {
            "new".to_string()
        } else {
            to_snake_case(&method.name)
        };
        *counts.entry(base.clone()).or_insert(0) += 1;
        raw_names.push(base);
    }

    let mut seen: HashMap<String, usize> = HashMap::new();
    let mut final_names = Vec::with_capacity(methods.len());

    for name in raw_names {
        let total = counts[&name];
        if total == 1 {
            final_names.push(escape_rust_keyword(&name));
        } else {
            let index = seen.entry(name.clone()).or_insert(0);
            let final_name = if *index == 0 {
                name.clone()
            } else {
                format!("{}_{}", name, index)
            };
            *index += 1;
            final_names.push(escape_rust_keyword(&final_name));
        }
    }

    final_names
}

fn emit_method(out: &mut String, class: &ClassModel, method: &MethodModel, rust_name: &str) {
    let is_static = method.is_static;
    let is_constructor = method.is_constructor;
    let sig = &method.signature;

    // Doc comment
    out.push_str(&format!(
        "    /// JNI call for `{}`: `{}`\n",
        method.name, method.descriptor
    ));

    // Function signature
    out.push_str(&format!("    pub unsafe fn {}(", rust_name));

    let mut params_rust = Vec::new();
    if !is_static && !is_constructor {
        params_rust.push("&self".to_string());
    }
    params_rust.push("env: *mut jni::JNIEnv".to_string());

    for (p_idx, param) in sig.parameters.iter().enumerate() {
        let p_name = format!("arg_{}", p_idx);
        let p_type = param.rust_type_string();
        params_rust.push(format!("{}: {}", p_name, p_type));
    }

    out.push_str(&params_rust.join(", "));
    out.push(')');

    let return_type_str = if is_constructor {
        class.simple_name.clone()
    } else {
        sig.return_type.rust_type_string()
    };

    if return_type_str == "()" {
        out.push_str(" {\n");
    } else {
        out.push_str(&format!(" -> {} {{\n", return_type_str));
    }

    // Method ID caching
    out.push_str("        static METHOD_ID: AtomicPtr<std::ffi::c_void> = AtomicPtr::new(std::ptr::null_mut());\n");
    out.push_str("        let mut mid = METHOD_ID.load(Ordering::Relaxed) as jni::jmethodID;\n");
    out.push_str("        if mid.is_null() {\n");
    out.push_str("            let clazz = Self::get_class(env);\n");
    out.push_str("            if !clazz.is_null() {\n");
    out.push_str(&format!(
        "                let name = c\"{}\";\n",
        method.name
    ));
    out.push_str(&format!(
        "                let sig = c\"{}\";\n",
        method.descriptor
    ));

    if is_static {
        out.push_str("                mid = ((**env).GetStaticMethodID)(env, clazz, name.as_ptr(), sig.as_ptr());\n");
    } else {
        out.push_str("                mid = ((**env).GetMethodID)(env, clazz, name.as_ptr(), sig.as_ptr());\n");
    }

    out.push_str("                if !mid.is_null() {\n");
    out.push_str(
        "                    METHOD_ID.store(mid as *mut std::ffi::c_void, Ordering::Release);\n",
    );
    out.push_str("                }\n");
    out.push_str("            }\n");
    out.push_str("        }\n");

    // Prepare arguments
    if sig.parameters.is_empty() {
        out.push_str("        let args: [jni::jvalue; 0] = [];\n");
    } else {
        out.push_str("        let args = [\n");
        for (p_idx, param) in sig.parameters.iter().enumerate() {
            let p_name = format!("arg_{}", p_idx);
            let union_field = match param {
                JvmType::Primitive(PrimitiveType::Boolean) => {
                    format!("z: {} as jni::jboolean", p_name)
                }
                JvmType::Primitive(PrimitiveType::Byte) => format!("b: {}", p_name),
                JvmType::Primitive(PrimitiveType::Char) => format!("c: {}", p_name),
                JvmType::Primitive(PrimitiveType::Short) => format!("s: {}", p_name),
                JvmType::Primitive(PrimitiveType::Int) => format!("i: {}", p_name),
                JvmType::Primitive(PrimitiveType::Long) => format!("j: {}", p_name),
                JvmType::Primitive(PrimitiveType::Float) => format!("f: {}", p_name),
                JvmType::Primitive(PrimitiveType::Double) => format!("d: {}", p_name),
                JvmType::Primitive(PrimitiveType::Void) => panic!("Void cannot be parameter"),
                JvmType::Object(_) | JvmType::Array(_) => format!("l: {} as jni::jobject", p_name),
            };
            out.push_str(&format!("            jni::jvalue {{ {} }},\n", union_field));
        }
        out.push_str("        ];\n");
    }

    // Call JNI
    let args_ptr = "if args.is_empty() { std::ptr::null() } else { args.as_ptr() }";

    if is_constructor {
        out.push_str("        let clazz = Self::get_class(env);\n");
        out.push_str(&format!(
            "        let raw = ((**env).NewObjectA)(env, clazz, mid, {});\n",
            args_ptr
        ));
        out.push_str("        Self::from_raw(raw)\n");
    } else if is_static {
        let suffix = sig.return_type.jni_call_method_suffix();
        let jni_fn = format!("CallStatic{}A", suffix);
        let clazz_expr = "Self::get_class(env)";

        if sig.return_type == JvmType::Primitive(PrimitiveType::Void) {
            out.push_str(&format!(
                "        ((**env).{})(env, {}, mid, {});\n",
                jni_fn, clazz_expr, args_ptr
            ));
        } else {
            out.push_str(&format!(
                "        let res = ((**env).{})(env, {}, mid, {});\n",
                jni_fn, clazz_expr, args_ptr
            ));
            out.push_str("        res\n");
        }
    } else {
        let suffix = sig.return_type.jni_call_method_suffix();
        let jni_fn = format!("Call{}A", suffix);

        if sig.return_type == JvmType::Primitive(PrimitiveType::Void) {
            out.push_str(&format!(
                "        ((**env).{})(env, self.raw, mid, {});\n",
                jni_fn, args_ptr
            ));
        } else {
            out.push_str(&format!(
                "        let res = ((**env).{})(env, self.raw, mid, {});\n",
                jni_fn, args_ptr
            ));
            out.push_str("        res\n");
        }
    }

    out.push_str("    }\n\n");
}

fn emit_field(
    out: &mut String,
    _class: &ClassModel,
    field: &FieldModel,
    used_names: &mut HashSet<String>,
) {
    let snake_name = to_snake_case(&field.name);
    let mut getter_name = format!("get_{}", snake_name);
    if used_names.contains(&getter_name) {
        getter_name.push_str("_field");
    }
    used_names.insert(getter_name.clone());

    let rust_type = field.jvm_type.rust_type_string();
    let is_static = field.is_static;

    // Field getter
    out.push_str(&format!(
        "    /// Field getter for `{}`: `{}`\n",
        field.name, field.descriptor
    ));

    if is_static {
        out.push_str(&format!(
            "    pub unsafe fn {}(env: *mut jni::JNIEnv) -> {} {{\n",
            getter_name, rust_type
        ));
    } else {
        out.push_str(&format!(
            "    pub unsafe fn {}(&self, env: *mut jni::JNIEnv) -> {} {{\n",
            getter_name, rust_type
        ));
    }

    out.push_str("        static FIELD_ID: AtomicPtr<std::ffi::c_void> = AtomicPtr::new(std::ptr::null_mut());\n");
    out.push_str("        let mut fid = FIELD_ID.load(Ordering::Relaxed) as jni::jfieldID;\n");
    out.push_str("        if fid.is_null() {\n");
    out.push_str("            let clazz = Self::get_class(env);\n");
    out.push_str("            if !clazz.is_null() {\n");
    out.push_str(&format!(
        "                let name = c\"{}\";\n",
        field.name
    ));
    out.push_str(&format!(
        "                let sig = c\"{}\";\n",
        field.descriptor
    ));

    if is_static {
        out.push_str("                fid = ((**env).GetStaticFieldID)(env, clazz, name.as_ptr(), sig.as_ptr());\n");
    } else {
        out.push_str("                fid = ((**env).GetFieldID)(env, clazz, name.as_ptr(), sig.as_ptr());\n");
    }

    out.push_str("                if !fid.is_null() {\n");
    out.push_str(
        "                    FIELD_ID.store(fid as *mut std::ffi::c_void, Ordering::Release);\n",
    );
    out.push_str("                }\n");
    out.push_str("            }\n");
    out.push_str("        }\n");

    let suffix = field.jvm_type.jni_field_suffix();
    if is_static {
        let jni_fn = format!("GetStatic{}", suffix);
        out.push_str(&format!(
            "        let res = ((**env).{})(env, Self::get_class(env), fid);\n",
            jni_fn
        ));
        out.push_str("        res\n");
    } else {
        let jni_fn = format!("Get{}", suffix);
        out.push_str(&format!(
            "        let res = ((**env).{})(env, self.raw, fid);\n",
            jni_fn
        ));
        out.push_str("        res\n");
    }
    out.push_str("    }\n\n");

    // If not final, emit setter
    if !field.is_final {
        let mut setter_name = format!("set_{}", snake_name);
        if used_names.contains(&setter_name) {
            setter_name.push_str("_field");
        }
        used_names.insert(setter_name.clone());

        out.push_str(&format!(
            "    /// Field setter for `{}`: `{}`\n",
            field.name, field.descriptor
        ));

        if is_static {
            out.push_str(&format!(
                "    pub unsafe fn {}(env: *mut jni::JNIEnv, val: {}) {{\n",
                setter_name, rust_type
            ));
        } else {
            out.push_str(&format!(
                "    pub unsafe fn {}(&self, env: *mut jni::JNIEnv, val: {}) {{\n",
                setter_name, rust_type
            ));
        }

        out.push_str("        static FIELD_ID: AtomicPtr<std::ffi::c_void> = AtomicPtr::new(std::ptr::null_mut());\n");
        out.push_str("        let mut fid = FIELD_ID.load(Ordering::Relaxed) as jni::jfieldID;\n");
        out.push_str("        if fid.is_null() {\n");
        out.push_str("            let clazz = Self::get_class(env);\n");
        out.push_str("            if !clazz.is_null() {\n");
        out.push_str(&format!(
            "                let name = c\"{}\";\n",
            field.name
        ));
        out.push_str(&format!(
            "                let sig = c\"{}\";\n",
            field.descriptor
        ));

        if is_static {
            out.push_str("                fid = ((**env).GetStaticFieldID)(env, clazz, name.as_ptr(), sig.as_ptr());\n");
        } else {
            out.push_str("                fid = ((**env).GetFieldID)(env, clazz, name.as_ptr(), sig.as_ptr());\n");
        }

        out.push_str("                if !fid.is_null() {\n");
        out.push_str(
            "                    FIELD_ID.store(fid as *mut std::ffi::c_void, Ordering::Release);\n",
        );
        out.push_str("                }\n");
        out.push_str("            }\n");
        out.push_str("        }\n");

        if is_static {
            let jni_fn = format!("SetStatic{}", suffix);
            out.push_str(&format!(
                "        ((**env).{})(env, Self::get_class(env), fid, val);\n",
                jni_fn
            ));
        } else {
            let jni_fn = format!("Set{}", suffix);
            out.push_str(&format!(
                "        ((**env).{})(env, self.raw, fid, val);\n",
                jni_fn
            ));
        }
        out.push_str("    }\n\n");
    }
}
